-- CoastSafe India PostgreSQL schema.
-- Safe to run on a new database or on the earlier Task 5 schema.
-- Existing beach and alert records are preserved. The legacy beach_name,
-- location, and alert_date columns are renamed to the clearer names used here.

BEGIN;

CREATE TABLE IF NOT EXISTS beaches (
  beach_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  state TEXT NOT NULL,
  location TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  facilities TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
  latitude NUMERIC(9, 6),
  longitude NUMERIC(9, 6),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT beaches_name_nonblank CHECK (btrim(name) <> ''),
  CONSTRAINT beaches_state_nonblank CHECK (btrim(state) <> ''),
  CONSTRAINT beaches_location_nonblank CHECK (btrim(location) <> ''),
  CONSTRAINT beaches_latitude_range CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
  CONSTRAINT beaches_longitude_range CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180)
);

-- Upgrade the earlier schema without deleting its data.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = current_schema() AND table_name = 'beaches' AND column_name = 'beach_name'
  ) AND NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = current_schema() AND table_name = 'beaches' AND column_name = 'name'
  ) THEN
    ALTER TABLE beaches RENAME COLUMN beach_name TO name;
  END IF;

  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = current_schema() AND table_name = 'alerts' AND column_name = 'location'
  ) AND NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = current_schema() AND table_name = 'alerts' AND column_name = 'affected_location'
  ) THEN
    ALTER TABLE alerts RENAME COLUMN location TO affected_location;
  END IF;

  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = current_schema() AND table_name = 'alerts' AND column_name = 'alert_date'
  ) AND NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = current_schema() AND table_name = 'alerts' AND column_name = 'issued_at'
  ) THEN
    ALTER TABLE alerts RENAME COLUMN alert_date TO issued_at;
  END IF;
END
$$;

ALTER TABLE beaches ADD COLUMN IF NOT EXISTS description TEXT NOT NULL DEFAULT '';
ALTER TABLE beaches ADD COLUMN IF NOT EXISTS facilities TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[];
ALTER TABLE beaches ADD COLUMN IF NOT EXISTS latitude NUMERIC(9, 6);
ALTER TABLE beaches ADD COLUMN IF NOT EXISTS longitude NUMERIC(9, 6);
ALTER TABLE beaches ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE beaches ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP;

CREATE TABLE IF NOT EXISTS alerts (
  alert_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  beach_id BIGINT REFERENCES beaches(beach_id) ON DELETE SET NULL,
  title TEXT NOT NULL,
  alert_type TEXT NOT NULL DEFAULT 'other',
  severity TEXT NOT NULL DEFAULT 'unknown',
  description TEXT NOT NULL,
  affected_location TEXT NOT NULL,
  source TEXT NOT NULL DEFAULT 'Unknown source',
  issued_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at TIMESTAMPTZ,
  verification_status TEXT NOT NULL DEFAULT 'unverified',
  verified_by TEXT,
  verified_at TIMESTAMPTZ,
  is_demo BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE alerts ADD COLUMN IF NOT EXISTS alert_type TEXT NOT NULL DEFAULT 'other';
ALTER TABLE alerts ADD COLUMN IF NOT EXISTS severity TEXT NOT NULL DEFAULT 'unknown';
ALTER TABLE alerts ADD COLUMN IF NOT EXISTS source TEXT NOT NULL DEFAULT 'Unknown source';
ALTER TABLE alerts ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE alerts ADD COLUMN IF NOT EXISTS expires_at TIMESTAMPTZ;
ALTER TABLE alerts ADD COLUMN IF NOT EXISTS verification_status TEXT NOT NULL DEFAULT 'unverified';
ALTER TABLE alerts ADD COLUMN IF NOT EXISTS verified_by TEXT;
ALTER TABLE alerts ADD COLUMN IF NOT EXISTS verified_at TIMESTAMPTZ;
ALTER TABLE alerts ADD COLUMN IF NOT EXISTS is_demo BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE alerts ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP;

-- Mark the previous sample exercise rows as demo data during an upgrade.
UPDATE alerts
SET title = CASE WHEN title ILIKE '[DEMO]%' THEN title ELSE '[DEMO] ' || title END,
    alert_type = 'training_scenario',
    severity = 'unknown',
    source = 'CoastSafe India demo data (not an authority)',
    updated_at = issued_at,
    expires_at = COALESCE(expires_at, issued_at + INTERVAL '6 hours'),
    verification_status = 'unverified',
    verified_by = NULL,
    verified_at = NULL,
    is_demo = TRUE
WHERE title ILIKE 'Sample exercise:%'
   OR description ILIKE '%Illustrative training scenario%';

CREATE TABLE IF NOT EXISTS environmental_observations (
  observation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  beach_id BIGINT NOT NULL REFERENCES beaches(beach_id) ON DELETE CASCADE,
  observation_type TEXT NOT NULL CHECK (observation_type IN ('weather', 'ocean')),
  measurement TEXT NOT NULL,
  value NUMERIC(12, 3) NOT NULL,
  unit TEXT NOT NULL,
  source TEXT NOT NULL,
  source_url TEXT,
  recorded_at TIMESTAMPTZ NOT NULL,
  valid_until TIMESTAMPTZ,
  verification_status TEXT NOT NULL DEFAULT 'unverified'
    CHECK (verification_status IN ('unverified', 'verified')),
  verified_by TEXT,
  verified_at TIMESTAMPTZ,
  is_demo BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT environmental_observation_text_required CHECK (
    btrim(measurement) <> '' AND btrim(unit) <> '' AND btrim(source) <> ''
  ),
  CONSTRAINT environmental_observation_validity_window CHECK (
    valid_until IS NULL OR valid_until > recorded_at
  ),
  CONSTRAINT environmental_observation_demo_unverified CHECK (
    NOT is_demo OR verification_status = 'unverified'
  ),
  CONSTRAINT environmental_observation_verified_complete CHECK (
    verification_status <> 'verified' OR (
      NOT is_demo
      AND verified_by IS NOT NULL AND btrim(verified_by) <> ''
      AND verified_at IS NOT NULL
      AND lower(btrim(source)) <> 'unknown source'
      AND valid_until IS NOT NULL AND valid_until > recorded_at
    )
  )
);

CREATE TABLE IF NOT EXISTS suitability_assessments (
  assessment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  beach_id BIGINT NOT NULL REFERENCES beaches(beach_id) ON DELETE CASCADE,
  activity TEXT NOT NULL CHECK (activity IN ('swimming', 'surfing', 'boating')),
  status TEXT NOT NULL CHECK (
    status IN ('suitable', 'caution', 'not_suitable', 'insufficient_data', 'unknown')
  ),
  reason TEXT NOT NULL,
  source TEXT NOT NULL,
  assessed_at TIMESTAMPTZ NOT NULL,
  expires_at TIMESTAMPTZ,
  verification_status TEXT NOT NULL DEFAULT 'unverified'
    CHECK (verification_status IN ('unverified', 'verified')),
  verified_by TEXT,
  verified_at TIMESTAMPTZ,
  is_demo BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT suitability_text_required CHECK (
    btrim(reason) <> '' AND btrim(source) <> ''
  ),
  CONSTRAINT suitability_expiry_after_assessment CHECK (
    expires_at IS NULL OR expires_at > assessed_at
  ),
  CONSTRAINT suitability_demo_unverified CHECK (
    NOT is_demo OR verification_status = 'unverified'
  ),
  CONSTRAINT suitability_conclusive_status_verified CHECK (
    status NOT IN ('suitable', 'caution', 'not_suitable')
    OR verification_status = 'verified'
  ),
  CONSTRAINT suitability_verified_complete CHECK (
    verification_status <> 'verified' OR (
      NOT is_demo
      AND verified_by IS NOT NULL AND btrim(verified_by) <> ''
      AND verified_at IS NOT NULL
      AND lower(btrim(source)) <> 'unknown source'
      AND expires_at IS NOT NULL AND expires_at > assessed_at
    )
  )
);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'beaches_name_nonblank' AND conrelid = 'beaches'::regclass
  ) THEN
    ALTER TABLE beaches ADD CONSTRAINT beaches_name_nonblank CHECK (btrim(name) <> '');
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'beaches_state_nonblank' AND conrelid = 'beaches'::regclass
  ) THEN
    ALTER TABLE beaches ADD CONSTRAINT beaches_state_nonblank CHECK (btrim(state) <> '');
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'beaches_location_nonblank' AND conrelid = 'beaches'::regclass
  ) THEN
    ALTER TABLE beaches ADD CONSTRAINT beaches_location_nonblank CHECK (btrim(location) <> '');
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'beaches_latitude_range' AND conrelid = 'beaches'::regclass
  ) THEN
    ALTER TABLE beaches ADD CONSTRAINT beaches_latitude_range
      CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'beaches_longitude_range' AND conrelid = 'beaches'::regclass
  ) THEN
    ALTER TABLE beaches ADD CONSTRAINT beaches_longitude_range
      CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'beaches_coordinates_pair' AND conrelid = 'beaches'::regclass
  ) THEN
    ALTER TABLE beaches ADD CONSTRAINT beaches_coordinates_pair
      CHECK ((latitude IS NULL) = (longitude IS NULL));
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'alerts_type_allowed' AND conrelid = 'alerts'::regclass
  ) THEN
    ALTER TABLE alerts ADD CONSTRAINT alerts_type_allowed
      CHECK (alert_type IN ('weather', 'wave', 'current', 'water_quality', 'access', 'training_scenario', 'general', 'other'));
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'alerts_severity_allowed' AND conrelid = 'alerts'::regclass
  ) THEN
    ALTER TABLE alerts ADD CONSTRAINT alerts_severity_allowed
      CHECK (severity IN ('info', 'warning', 'critical', 'unknown'));
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'alerts_verification_status_allowed' AND conrelid = 'alerts'::regclass
  ) THEN
    ALTER TABLE alerts ADD CONSTRAINT alerts_verification_status_allowed
      CHECK (verification_status IN ('unverified', 'verified'));
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'alerts_required_text' AND conrelid = 'alerts'::regclass
  ) THEN
    ALTER TABLE alerts ADD CONSTRAINT alerts_required_text
      CHECK (btrim(title) <> '' AND btrim(description) <> '' AND btrim(affected_location) <> '' AND btrim(source) <> '');
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'alerts_expiry_after_issue' AND conrelid = 'alerts'::regclass
  ) THEN
    ALTER TABLE alerts ADD CONSTRAINT alerts_expiry_after_issue
      CHECK (expires_at IS NULL OR expires_at > issued_at);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'alerts_updated_after_issue' AND conrelid = 'alerts'::regclass
  ) THEN
    ALTER TABLE alerts ADD CONSTRAINT alerts_updated_after_issue
      CHECK (updated_at >= issued_at);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'alerts_demo_unverified' AND conrelid = 'alerts'::regclass
  ) THEN
    ALTER TABLE alerts ADD CONSTRAINT alerts_demo_unverified
      CHECK (NOT is_demo OR verification_status = 'unverified');
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'alerts_verified_complete' AND conrelid = 'alerts'::regclass
  ) THEN
    ALTER TABLE alerts ADD CONSTRAINT alerts_verified_complete CHECK (
      verification_status <> 'verified' OR (
        NOT is_demo
        AND severity <> 'unknown'
        AND btrim(source) <> '' AND lower(btrim(source)) <> 'unknown source'
        AND verified_by IS NOT NULL AND btrim(verified_by) <> ''
        AND verified_at IS NOT NULL
        AND expires_at IS NOT NULL AND expires_at > issued_at
      )
    );
  END IF;
END
$$;

CREATE UNIQUE INDEX IF NOT EXISTS beaches_name_state_idx
  ON beaches (name, state);
CREATE INDEX IF NOT EXISTS beaches_state_name_idx
  ON beaches (state, name);
CREATE INDEX IF NOT EXISTS alerts_beach_issued_idx
  ON alerts (beach_id, issued_at DESC);
CREATE INDEX IF NOT EXISTS alerts_verified_issued_idx
  ON alerts (issued_at DESC)
  WHERE verification_status = 'verified' AND is_demo = FALSE;
CREATE INDEX IF NOT EXISTS environmental_beach_recorded_idx
  ON environmental_observations (beach_id, recorded_at DESC);
CREATE INDEX IF NOT EXISTS environmental_measurement_recorded_idx
  ON environmental_observations (measurement, recorded_at DESC);
CREATE INDEX IF NOT EXISTS suitability_beach_activity_assessed_idx
  ON suitability_assessments (beach_id, activity, assessed_at DESC);

CREATE OR REPLACE VIEW current_verified_environment AS
SELECT observation_id, beach_id, observation_type, measurement, value, unit,
       source, source_url, recorded_at, valid_until
FROM environmental_observations
WHERE verification_status = 'verified'
  AND is_demo = FALSE
  AND valid_until > CURRENT_TIMESTAMP;

CREATE OR REPLACE VIEW current_verified_suitability AS
SELECT assessment_id, beach_id, activity, status, reason, source,
       assessed_at, expires_at
FROM suitability_assessments
WHERE verification_status = 'verified'
  AND is_demo = FALSE
  AND status IN ('suitable', 'caution', 'not_suitable')
  AND expires_at > CURRENT_TIMESTAMP;

CREATE OR REPLACE VIEW active_verified_alerts AS
SELECT alert_id, beach_id, title, alert_type, severity, description,
       affected_location, source, issued_at, updated_at, expires_at
FROM alerts
WHERE verification_status = 'verified'
  AND is_demo = FALSE
  AND issued_at <= CURRENT_TIMESTAMP
  AND expires_at > CURRENT_TIMESTAMP;

COMMENT ON TABLE beaches IS 'Descriptive beach records. Coordinates are optional map pins, not safety readings.';
COMMENT ON TABLE environmental_observations IS 'Source-attributed numeric weather and ocean readings; this project seeds no readings.';
COMMENT ON TABLE suitability_assessments IS 'Time-limited activity assessments; conclusive statuses must be verified.';
COMMENT ON TABLE alerts IS 'Coastal notices. Demo rows are unverified and excluded from active_verified_alerts.';
COMMENT ON COLUMN alerts.affected_location IS 'Beach, locality, or coastal area affected by the notice.';
COMMENT ON COLUMN alerts.issued_at IS 'Date and time the notice was issued.';
COMMENT ON COLUMN alerts.is_demo IS 'TRUE identifies illustrative development data, never an official notice.';

COMMIT;

-- CoastSafe India PostgreSQL schema
-- Create the database first, then apply this file:
--   createdb coastsafe_india
--   psql -d coastsafe_india -f database/schema.sql

CREATE TABLE IF NOT EXISTS beaches (
  beach_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  beach_name TEXT NOT NULL,
  state TEXT NOT NULL,
  location TEXT NOT NULL,
  latitude NUMERIC(9, 6),
  longitude NUMERIC(9, 6),
  description TEXT NOT NULL DEFAULT '',
  facilities TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT beaches_latitude_range CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
  CONSTRAINT beaches_longitude_range CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180)
);

CREATE TABLE IF NOT EXISTS alerts (
  alert_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  beach_id BIGINT REFERENCES beaches(beach_id) ON DELETE SET NULL,
  title TEXT NOT NULL,
  description TEXT NOT NULL,
  location TEXT NOT NULL,
  alert_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS alerts_beach_date_idx
  ON alerts (beach_id, alert_date DESC);

COMMENT ON TABLE beaches IS 'Indian beaches shown in the CoastSafe India app.';
COMMENT ON COLUMN beaches.beach_id IS 'Unique database ID for the beach.';
COMMENT ON COLUMN beaches.beach_name IS 'Display name of the beach.';
COMMENT ON COLUMN beaches.state IS 'Indian state or union territory containing the beach.';
COMMENT ON COLUMN beaches.location IS 'Human-readable locality, district, or region.';
COMMENT ON COLUMN beaches.latitude IS 'Optional latitude in decimal degrees.';
COMMENT ON COLUMN beaches.longitude IS 'Optional longitude in decimal degrees.';
COMMENT ON COLUMN beaches.description IS 'Short description shown in the app.';
COMMENT ON COLUMN beaches.facilities IS 'Facilities available at the beach, stored as a simple text array.';
COMMENT ON COLUMN beaches.created_at IS 'Time the row was created.';
COMMENT ON COLUMN beaches.updated_at IS 'Time the row was last updated; updated by the application.';

COMMENT ON TABLE alerts IS 'Coastal alerts and advisories. A row may target one beach or a wider area.';
COMMENT ON COLUMN alerts.alert_id IS 'Unique database ID for the alert.';
COMMENT ON COLUMN alerts.beach_id IS 'Optional beach reference; NULL means the alert applies to a wider area.';
COMMENT ON COLUMN alerts.title IS 'Short alert heading.';
COMMENT ON COLUMN alerts.description IS 'Details of the alert.';
COMMENT ON COLUMN alerts.location IS 'Affected beach, locality, or coastal region.';
COMMENT ON COLUMN alerts.alert_date IS 'Date and time the alert was issued, stored with its time zone.';

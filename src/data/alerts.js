export function categoryMeta(categoryId) {
  return alertCategories.find((item) => item.id === categoryId) || alertCategories[0];
}

export function alertsForBeach(beach) {
  if (!beach) return [];
  return alerts.filter((alert) => alert.beachIds?.includes(beach.id));
}

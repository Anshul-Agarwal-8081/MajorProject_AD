function reading({
  wave,
  waveDir,
  swell,
  period,
  current,
  currentDir,
  wind,
  windDir,
  temp,
  rain = 0,
  weather,
}) {
  return {
    waveHeightM: wave,
    waveDirection: waveDir,
    swellHeightM: swell,
    swellPeriodS: period,
    currentSpeedMs: current,
    currentDirection: currentDir,
    windSpeedKmh: wind,
    windDirection: windDir,
    temperatureC: temp,
    precipitationMm: rain,
    weather,
  };
}

